import test from "node:test";
import assert from "node:assert/strict";
import { mkdtempSync } from "node:fs";
import { join } from "node:path";
import { tmpdir } from "node:os";

process.env.AGENT_DB_PATH = join(mkdtempSync(join(tmpdir(), "agent-coordinate-test-")), "agents.sqlite");
const action = await import("../src/app/api/action/route.ts");
const run = await import("../src/app/api/run/route.ts");
const store = await import("../src/lib/store.ts");
const base = "http://127.0.0.1:3000";
async function post(handler, path, body) {
  const req = new Request(`${base}${path}`, { method: "POST", headers: { host: "127.0.0.1:3000", origin: base, "content-type": "application/json" }, body: JSON.stringify(body) });
  const response = await handler.POST(req);
  return { status: response.status, body: await response.json() };
}

test("双领域独立协调：预算、旧成果、偏好和暂停", async () => {
  const career = await post(action, "/api/action", { type: "goal.create", domain: "career", title: "岗位面试", detail: "用真实经历练习", priority: 5 });
  const english = await post(action, "/api/action", { type: "goal.create", domain: "english", title: "英语表达", detail: "练习清晰表达", priority: 1 });
  assert.equal(career.status, 200);
  assert.equal(english.status, 200);
  const initial = (await post(action, "/api/action", { type: "plan.preview", budget: 90 })).body.proposal;
  assert.equal(initial.items.length, 2);
  assert.equal(initial.items.reduce((n, item) => n + item.minutes, 0), 90);
  assert.equal(store.state().tasks.length, 0, "预览不能改动任务");
  const adopted = await post(action, "/api/action", { type: "plan.accept", budget: 90, token: initial.token });
  assert.equal(adopted.status, 200);
  const careerTask = adopted.body.state.tasks.find(t => t.agent_id === "career");
  const englishTask = adopted.body.state.tasks.find(t => t.agent_id === "english");
  await post(action, "/api/action", { type: "task.draft", id: englishTask.id, draft: "saved English draft" });
  const careerRun = store.createRun(careerTask.id, "career", "career-one", "my career answer", "mock-model", []);
  store.completeRun(careerRun, careerTask.id, "success", "引用本次回答的反馈", null, "练习结构化回答");
  assert.equal((await post(action, "/api/action", { type: "task.finish", id: careerTask.id })).status, 200);
  const memory = await post(action, "/api/action", { type: "memory.accept", taskId: careerTask.id, text: "练习结构化回答" });
  assert.equal(memory.status, 200);
  assert.equal(store.getMemories(english.body.id, "english").length, 0, "求职记忆不得进入英语角色");
  const tooSmall = (await post(action, "/api/action", { type: "plan.preview", budget: 30 })).body.proposal;
  assert.ok(tooSmall.lockedMinutes > tooSmall.budget);
  assert.equal((await post(action, "/api/action", { type: "plan.accept", budget: 30, token: tooSmall.token })).status, 409);
  assert.equal(store.state().budget, 90);
  const shorter = (await post(action, "/api/action", { type: "plan.preview", budget: 85 })).body.proposal;
  assert.equal(shorter.items.reduce((n, item) => n + item.minutes, 0) + shorter.lockedMinutes, 85);
  assert.notEqual(shorter.items.find(i => i.agentId === "career").prompt, careerTask.prompt);
  assert.equal(store.getTask(englishTask.id).status, "waiting", "采用前原任务不变");
  const changed = await post(action, "/api/action", { type: "plan.accept", budget: 85, token: shorter.token });
  assert.equal(changed.status, 200);
  assert.equal(store.getTask(careerTask.id).status, "done");
  assert.equal(store.getTask(englishTask.id).status, "superseded");
  assert.equal(store.getTask(englishTask.id).draft, "saved English draft");
  assert.equal(store.getRun(careerRun).status, "success");
  const priority = (await post(action, "/api/action", { type: "plan.preview", budget: 130 })).body.proposal;
  await post(action, "/api/action", { type: "agent.update", id: "coordinator", enabled: true, preference: "balanced" });
  const balanced = (await post(action, "/api/action", { type: "plan.preview", budget: 130 })).body.proposal;
  assert.notEqual(priority.items.find(i => i.agentId === "english").minutes, balanced.items.find(i => i.agentId === "english").minutes);
  await post(action, "/api/action", { type: "agent.update", id: "coordinator", enabled: false, preference: "balanced" });
  assert.equal((await post(action, "/api/action", { type: "plan.preview", budget: 130 })).status, 409);
  await post(action, "/api/action", { type: "agent.update", id: "coordinator", enabled: true, preference: "balanced" });
  await post(action, "/api/action", { type: "agent.update", id: "career", enabled: false, preference: "" });
  const withoutCareer = (await post(action, "/api/action", { type: "plan.preview", budget: 130 })).body.proposal;
  assert.equal(withoutCareer.items.some(i => i.agentId === "career"), false);
  const waitingCareer = changed.body.state.tasks.find(t => t.agent_id === "career" && t.status === "waiting");
  assert.equal((await post(run, "/api/run", { type: "submit", taskId: waitingCareer.id, answer: "blocked", submissionId: "blocked-career" })).status, 409);

  await post(action, "/api/action", { type: "agent.update", id: "career", enabled: true, preference: "" });
  assert.equal((await post(action, "/api/action", { type: "goal.schedule", id: career.body.id, active: false })).status, 200);
  assert.equal(store.state().goals.find(g => g.id === career.body.id).active, 0);
  const pausedGoalPlan = (await post(action, "/api/action", { type: "plan.preview", budget: 130 })).body.proposal;
  assert.equal(pausedGoalPlan.items.some(item => item.goalId === career.body.id), false);
  assert.equal(pausedGoalPlan.lockedMinutes, careerTask.minutes, "已完成任务仍占用今日预算");
  assert.equal(store.getTask(careerTask.id).status, "done");
  const fresh = await post(action, "/api/action", { type: "goal.create", domain: "career", title: "新的个人目标", detail: "", priority: 5 });
  assert.equal(fresh.status, 200);
  const nextPlan = (await post(action, "/api/action", { type: "plan.preview", budget: 130 })).body.proposal;
  assert.equal(nextPlan.items.some(item => item.goalId === fresh.body.id), true, "完成旧任务后仍可安排新目标");
  assert.equal(nextPlan.items.some(item => item.goalId === career.body.id), false);
  assert.equal((await post(action, "/api/action", { type: "goal.schedule", id: "missing", active: false })).status, 404);
  assert.equal((await post(action, "/api/action", { type: "goal.schedule", id: career.body.id, active: true })).status, 200);
  assert.equal((await post(action, "/api/action", { type: "plan.preview", budget: 130 })).body.proposal.items.some(item => item.goalId === career.body.id), true);
});
